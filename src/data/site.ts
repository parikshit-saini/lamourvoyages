export function matchesTourFilters(tour: Tour, filters: TourFilters) {
  const nights = Number.parseInt(tour.duration, 10);
  const inDuration =
    !filters.duration ||
    (filters.duration === "short" && nights <= 5) ||
    (filters.duration === "medium" && nights >= 6 && nights <= 8) ||
    (filters.duration === "long" && nights >= 9);

  return (
    inDuration &&
    (!filters.region || tour.regions.includes(filters.region)) &&
    (!filters.style || tour.style === filters.style)
  );
}

